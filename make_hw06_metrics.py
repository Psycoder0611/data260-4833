"""HW6 Part 3: build reports/hw06/METRICS.md from the raw experiment files (no hand-typed numbers)."""
import csv
import json
import sys
from pathlib import Path

from hw6 import config

RAW_DIR = config.REPO_ROOT / "reports" / "hw06" / "raw"
OUT_FILE = config.REPO_ROOT / "reports" / "hw06" / "METRICS.md"
ORDER = ["n4", "n12", "n30", "compress"]
INPUT_PRICE_PER_MILLION = 1.0
OUTPUT_PRICE_PER_MILLION = 5.0
CONVERSATIONS = 10_000
TURNS_PER_CONVERSATION = 30
SCORE_TIE_MARGIN = 0.2


def load_summary() -> dict:
    """Read raw/summary.json written by the experiment runner."""
    path = RAW_DIR / "summary.json"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found. Run run_hw06_memory_experiment.py first.")
    return json.loads(path.read_text(encoding="utf-8"))


def component_means(key: str) -> dict:
    """Mean per-turn tokens for each prompt part, from turns_<key>.csv."""
    columns = [
        "system_primer_tokens", "long_term_tokens", "short_term_tokens",
        "episodic_tokens", "current_message_tokens", "aux_prompt_tokens", "aux_completion_tokens",
    ]
    with (RAW_DIR / f"turns_{key}.csv").open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    return {name: round(sum(float(row[name]) for row in rows) / len(rows), 1) for name in columns}


def conversation_cost(entry: dict) -> dict:
    """Cost of 10,000 conversations of 30 turns, counting reply calls and background calls."""
    input_tokens = entry["total_prompt_tokens"] + entry["total_aux_prompt_tokens"]
    output_tokens = entry["total_completion_tokens"] + entry["total_aux_completion_tokens"]
    scale = CONVERSATIONS * TURNS_PER_CONVERSATION / entry["turns"]
    input_cost = input_tokens * scale * INPUT_PRICE_PER_MILLION / 1_000_000
    output_cost = output_tokens * scale * OUTPUT_PRICE_PER_MILLION / 1_000_000
    return {
        "input_tokens": int(input_tokens * scale),
        "output_tokens": int(output_tokens * scale),
        "input_cost": input_cost,
        "output_cost": output_cost,
        "total_cost": input_cost + output_cost,
    }


def pick_best_and_worst(summary: dict, costs: dict) -> tuple:
    """Best = highest probe score (ties within 0.2 go to the cheaper one); worst = lowest score
    (ties go to the more expensive one). Applied to the three SHORT_TERM_N settings only."""
    keys = [key for key in ORDER if key in summary and key != "compress"]
    top = max(summary[key]["mean_probe_score"] for key in keys)
    near_top = [key for key in keys if round(top - summary[key]["mean_probe_score"], 6) <= SCORE_TIE_MARGIN]
    best = min(near_top, key=lambda key: costs[key]["total_cost"])
    bottom = min(summary[key]["mean_probe_score"] for key in keys)
    near_bottom = [key for key in keys if round(summary[key]["mean_probe_score"] - bottom, 6) <= SCORE_TIE_MARGIN]
    worst = max(near_bottom, key=lambda key: costs[key]["total_cost"])
    return best, worst


def build_markdown(summary: dict) -> str:
    """Assemble the METRICS.md text."""
    keys = [key for key in ORDER if key in summary]
    costs = {key: conversation_cost(summary[key]) for key in keys}
    lines = ["# HW6 Metrics (generated by make_hw06_metrics.py from reports/hw06/raw/)", ""]

    lines += [
        "## Table 1 - Memory settings (30-message conversation, 5 probes)",
        "",
        "| Setting | Mean prompt tokens/turn | Mean latency (ms) | Probe quality (1-5) |",
        "|---|---|---|---|",
    ]
    for key in keys:
        item = summary[key]
        lines.append(
            f"| {item['label']} | {item['mean_prompt_tokens']} | {item['mean_latency_ms']} | {item['mean_probe_score']} |"
        )

    lines += ["", "## Table 2 - Where the prompt tokens go (mean per turn)", "",
              "Part sizes are the real prompt token count split in proportion to each part's text length.", "",
              "| Setting | System primer | Long-term summaries | Short-term window | Episodic facts | Current message |",
              "|---|---|---|---|---|---|"]
    for key in keys:
        parts = component_means(key)
        lines.append(
            f"| {summary[key]['label']} | {parts['system_primer_tokens']} | {parts['long_term_tokens']} | "
            f"{parts['short_term_tokens']} | {parts['episodic_tokens']} | {parts['current_message_tokens']} |"
        )

    lines += ["", "## Table 3 - Probe scores per question", "",
              "| Setting | P1 | P2 | P3 | P4 | P5 | Mean |", "|---|---|---|---|---|---|---|"]
    for key in keys:
        scores = summary[key]["probe_scores"]
        cells = " | ".join(str(scores.get(f"P{i}", "-")) for i in range(1, 6))
        lines.append(f"| {summary[key]['label']} | {cells} | {summary[key]['mean_probe_score']} |")

    if "compress" in summary and "n30" in summary:
        before, after = summary["n30"], summary["compress"]
        saved = before["mean_prompt_tokens"] - after["mean_prompt_tokens"]
        percent = 100 * saved / before["mean_prompt_tokens"] if before["mean_prompt_tokens"] else 0.0
        latency_change = after["mean_latency_ms"] - before["mean_latency_ms"]
        lines += ["", "## Table 4 - Compression policy vs SHORT_TERM_N=30", "",
                  "Policy: keep the last 6 messages word for word; for older messages in the window, drop assistant "
                  "replies and keep only shortened user messages as bullets.", "",
                  "| Measure | N=30 (before) | Compression (after) | Change |", "|---|---|---|---|",
                  f"| Mean prompt tokens/turn | {before['mean_prompt_tokens']} | {after['mean_prompt_tokens']} | "
                  f"{-saved:+.1f} ({-percent:+.1f}%) |",
                  f"| Probe quality (1-5) | {before['mean_probe_score']} | {after['mean_probe_score']} | "
                  f"{after['mean_probe_score'] - before['mean_probe_score']:+.2f} |",
                  f"| Mean latency (ms) | {before['mean_latency_ms']} | {after['mean_latency_ms']} | "
                  f"{latency_change:+.1f} ms |"]

    best, worst = pick_best_and_worst(summary, costs)
    lines += ["", f"## Table 5 - Cost of {CONVERSATIONS:,} conversations x {TURNS_PER_CONVERSATION} turns", "",
              f"Pricing: input ${INPUT_PRICE_PER_MILLION:.0f} per million tokens, output "
              f"${OUTPUT_PRICE_PER_MILLION:.0f} per million tokens. Tokens include the reply call and the "
              "background calls (episode extraction and summaries).", "",
              "| Setting | Input tokens | Output tokens | Input cost | Output cost | Total cost |",
              "|---|---|---|---|---|---|"]
    for key in keys:
        cost = costs[key]
        lines.append(
            f"| {summary[key]['label']} | {cost['input_tokens']:,} | {cost['output_tokens']:,} | "
            f"${cost['input_cost']:,.2f} | ${cost['output_cost']:,.2f} | ${cost['total_cost']:,.2f} |"
        )
    lines += ["",
              f"Best setting: **{summary[best]['label']}**. Worst setting: **{summary[worst]['label']}**.", "",
              "How they were chosen: best = highest mean probe score, and if several settings are within "
              f"{SCORE_TIE_MARGIN} points of the top, the cheapest of them. Worst = lowest mean probe score, "
              "and if several are within the same margin, the most expensive of them. The rule was fixed "
              "before the runs and is in make_hw06_metrics.py."]
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write METRICS.md and print it."""
    text = build_markdown(load_summary())
    OUT_FILE.write_text(text, encoding="utf-8")
    print(text)
    print(f"Wrote {OUT_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
